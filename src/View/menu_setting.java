    private void btn_diskonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_diskonActionPerformed
    try {
        // Minta input dari user
        String input = JOptionPane.showInputDialog(this, "Masukkan Diskon Baru (%):");

        if (input != null && !input.trim().isEmpty()) {
            // parsing ke double biar validasi angka
            double diskonBaru = Double.parseDouble(input);

            // bikin model_pengaturan
            model_pengaturan mp = new model_pengaturan();
            mp.setNama("diskon");              // sesuai field 'nama' di DB
            mp.setNilai(String.valueOf(diskonBaru));

            // simpan ke DB lewat dao
            dao_pengaturan dao = new dao_pengaturan(koneksi.getConnection());
            dao.updatePengaturan(mp);

            JOptionPane.showMessageDialog(this, 
                "Diskon berhasil diubah menjadi: " + diskonBaru + "%");
        } else {
            JOptionPane.showMessageDialog(this, "Input diskon tidak boleh kosong");
        }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Input diskon harus berupa angka");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Terjadi kesalahan: " + e.getMessage());
        }
    }//GEN-LAST:event_btn_diskonActionPerformed

